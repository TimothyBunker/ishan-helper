#!/usr/bin/env python3
"""
Simple search interface for slide content indexed by scripts/index_slides.py.
Usage:
  python3 scripts/query_slides.py "search query" -i slide_index.json
"""
import json
import sys

def load_index(index_file):
    try:
        with open(index_file, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        sys.exit(f"Error loading index file '{index_file}': {e}")

def search_slides(slides, query, max_results=5):
    q = query.lower()
    results = []
    for slide in slides:
        filename = slide.get("filename")
        for page in slide.get("pages", []):
            text = page.get("text", "")
            if q in text.lower():
                idx = text.lower().find(q)
                start = max(0, idx - 60)
                end = min(len(text), idx + len(q) + 60)
                snippet = text[start:end].replace("\n", " ")
                results.append({
                    "filename": filename,
                    "page": page.get("page_number"),
                    "snippet": snippet.strip()
                })
                if len(results) >= max_results:
                    return results
    return results

def main():
    import argparse
    parser = argparse.ArgumentParser(
        description="Search indexed slide content and print matching excerpts."
    )
    parser.add_argument(
        "query", help="Search query string"
    )
    parser.add_argument(
        "-i", "--index", default="slide_index.json",
        help="Index JSON file generated by index_slides.py"
    )
    parser.add_argument(
        "-n", "--max-results", type=int, default=5,
        help="Maximum number of results to display"
    )
    args = parser.parse_args()

    data = load_index(args.index)
    slides = data.get("slides", [])
    results = search_slides(slides, args.query, args.max_results)
    if not results:
        print("No matches found.")
        sys.exit(0)

    for res in results:
        print(f"{res['filename']} - page {res['page']}")
        print(f"...{res['snippet']}...")
        print()

if __name__ == "__main__":
    main()